"""Generate MSI completion events and NSIS compatibility registrations."""

import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape, quoteattr

NS = {'w': 'http://schemas.microsoft.com/wix/2006/wi'}
GROUPS = ('Audio', 'Video', 'Other')
# Separate components own the added aliases; existing MSI component identities
# and key paths remain unchanged. Keep these GUIDs stable across releases.
NSIS_COMPONENT_GUIDS = {
    'Audio': 'f8ec95fb-8490-482f-87ee-16bd7db9c9d3',
    'Video': 'cc7721f5-d8b6-49a4-9b2a-3b5f789757e5',
    'Other': '7930edd2-0812-4fbd-bd13-64a92603a454',
}
CAPABILITIES = r'Software\Clients\Media\VLC\Capabilities\FileAssociations'
# Keep registration/compatibility complete; only automatic default batches are
# filtered. Explicit requests and manual associations remain unrestricted.
BULK_DEFAULT_EXCLUSIONS = {'.mid', '.bin'}


def generate(source):
    root = ET.parse(source).getroot()
    groups = []
    components = []
    seen = set()
    for group in GROUPS:
        component = root.find(".//w:Component[@Id='Comp%sFileAssociation']" % group, NS)
        if component is None:
            raise ValueError('Missing association component: ' + group)
        extensions = []
        for value in component.findall('w:RegistryValue', NS):
            if value.get('Key') != CAPABILITIES:
                continue
            extension = value.get('Name', '')
            if not re.fullmatch(r'\.[a-z0-9]+', extension) or extension in seen:
                raise ValueError('Invalid or duplicate extension: ' + extension)
            seen.add(extension)
            extensions.append(extension)
        if not extensions:
            raise ValueError('Empty association component: ' + group)
        groups.append(extensions)
        components.append(component)

    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by msi-associations.py; do not edit. -->',
             '<Include xmlns="http://schemas.microsoft.com/wix/2006/wi">']

    # NSIS uninstall removes VLC.ext, while MSI uses VLC.ext.Document. Recreate
    # the old identifiers as ordinary registrations so a retained UserChoice
    # continues to resolve even when historical success skips the defaults worker.
    # Derive their metadata/commands from the existing inventory, not a second list.
    lines.append('  <DirectoryRef Id="APPLICATIONFOLDER">')
    for group, component, extensions in zip(GROUPS, components, groups):
        component_id = 'Comp%sNSISFileAssociation' % group
        lines.append('    <Component Id="%s" Guid="%s">' %
                     (component_id, NSIS_COMPONENT_GUIDS[group]))
        capabilities = {value.get('Name'): value.get('Value')
                        for value in component.findall('w:RegistryValue', NS)
                        if value.get('Key') == CAPABILITIES}
        # The first open command is the key path; keep that identity stable.
        for index, extension in enumerate(extensions):
            program_id = capabilities[extension]
            metadata = component.find("w:ProgId[@Id='%s']" % program_id, NS)
            command = component.find("w:RegistryValue[@Key='%s\\shell\\open\\command']" % program_id, NS)
            if metadata is None or command is None or command.get('Value') is None:
                raise ValueError('Missing ProgID registration: ' + str(program_id))
            legacy_id = 'VLC' + extension
            attributes = dict(metadata.attrib, Id=legacy_id)
            lines.append('      <ProgId %s />' % ' '.join(
                         key + '=' + quoteattr(value) for key, value in attributes.items()))
            lines.append('      <RegistryValue Root="HKCR" Key=%s Value=%s Type="string"%s />' %
                         (quoteattr(legacy_id + r'\shell\open\command'),
                          quoteattr(command.get('Value')), ' KeyPath="yes"' if index == 0 else ''))
        lines.append('    </Component>')
    lines.append('  </DirectoryRef>')
    # The verified ordinary-user worker owns persistent eligibility. Existing
    # related-product/NSIS migration detection and feature migration stay intact.
    eligible_install = ('UILevel = 5 AND ACTION = "INSTALL" AND NOT Installed AND NOT '
                        'REINSTALL AND NOT REMOVE AND NOT PATCH AND NOT '
                        'UPGRADINGPRODUCTCODE AND NOT RESUME AND NOT Preselected')
    # ControlEvent.Argument is limited to 255 characters. Keep the complete
    # inventories in private Property values (unbounded), and publish references.
    for mask in range(1, 8):
        extensions = [extension for index, group in enumerate(groups)
                      if mask & (1 << index) for extension in group
                      if extension not in BULK_DEFAULT_EXCLUSIONS]
        lines.append('  <Property Id="VlcAssociationBatch%d" Value=%s />' %
                     (mask, quoteattr(','.join(extensions))))
    lines += [
        '  <!-- Private, client-side eligibility survives ExecuteAction. Capture the',
        '       original full UI here, not INSTALLLEVEL (feature selection level). -->',
        '  <CustomAction Id="VlcResetAssociationEligibility" Property="VlcAssociationEligible" Value="" />',
        '  <CustomAction Id="VlcSetAssociationEligibility" Property="VlcAssociationEligible" Value="1" />',
        '  <InstallUISequence>',
        '    <Custom Action="VlcResetAssociationEligibility" Before="AppSearch">1</Custom>',
        '    <Custom Action="VlcSetAssociationEligibility" After="CostFinalize">%s</Custom>' % escape(eligible_install),
        '  </InstallUISequence>',
        '  <!-- Client impersonation delegates identity checks to the existing CLI.',
        '       No wait/result claim, elevated service action, retry or termination. -->',
        '  <CustomAction Id="VlcSetDefaultAssociations" FileKey="vlc.exe"',
        '                ExeCommand="--win32-set-default-associations-once=[VlcAssociationExtensions]"',
        '                Execute="immediate" Impersonate="yes" Return="asyncNoWait" />',
        '  <UI>',
    ]

    # Finish events follow Order, not their position in the generated XML.
    def publish(order, condition, **attrs):
        attributes = dict(Dialog='ExitDialog', Control='Finish', Order=str(order), **attrs)
        lines.append('    <Publish %s>%s</Publish>' %
                     (' '.join(key + '=' + quoteattr(value) for key, value in attributes.items()), escape(condition)))

    # Overwrite any stale list. Each exact feature mask selects one literal list;
    # absent/unknown states cannot accidentally include an unchecked group.
    # In an MSI SetProperty event, {} clears the property instead of storing braces.
    publish(10, '1', Property='VlcAssociationExtensions', Value='{}')
    publish(9, 'Installed OR REINSTALL OR REMOVE '
            'OR PATCH OR UPGRADINGPRODUCTCODE OR RESUME',
            Property='VlcAssociationEligible', Value='{}')
    eligible = 'VlcAssociationEligible = 1 AND NOT VlcAssociationAttempted'
    # Use final action states (&), not prior states (!): local=3, absent=2.
    for mask in range(1, 8):
        states = ' AND '.join('(&%sFILEASSOCIATION = %d)' %
                             (group.upper(), 3 if mask & (1 << index) else 2)
                             for index, group in enumerate(GROUPS))
        publish(10 + mask, eligible + ' AND ' + states,
                Property='VlcAssociationExtensions', Value='[VlcAssociationBatch%d]' % mask)
    # Latch before launch, so even launch failure/repeated Finish cannot retry.
    publish(20, 'VlcAssociationExtensions', Property='VlcAssociationAttempted', Value='1')
    publish(21, 'VlcAssociationExtensions AND VlcAssociationAttempted = 1',
            Event='DoAction', Value='VlcSetDefaultAssociations')
    publish(22, 'VlcAssociationExtensions', Property='VlcAssociationExtensions', Value='{}')
    lines += ['  </UI>', '</Include>', '']
    return '\n'.join(lines)


def generate_nsis(source, extensions):
    # Use declared handlers, not capabilities: .amrec currently advertises
    # VLC.ts.Document but also declares its own VLC.amrec.Document handler.
    root = ET.parse(source).getroot()
    msi_extensions = set()
    for program_id in root.findall('.//w:ProgId', NS):
        match = re.fullmatch(r'VLC(\.[a-z0-9]+)\.Document', program_id.get('Id', ''))
        if match:
            msi_extensions.add(match[1])

    macros = dict(re.findall(r'!macro (\w+) _action\n(.*?)!macroend',
                             extensions.read_text(), re.S))

    def collect(name, parents=()):
        if name not in macros or name in parents:
            raise ValueError('Invalid NSIS extension macro: ' + name)
        result = set()
        for line in macros[name].splitlines():
            line = line.partition(';')[0].strip()
            if not line:
                continue
            direct = re.fullmatch(r'\s*!insertmacro \$\{_action\} \w+ "([^"\n]+)"', line)
            nested = re.fullmatch(r'\s*!insertmacro (\w+) \$\{_action\}', line)
            if direct:
                result.add(direct[1])
            elif nested:
                result.update(collect(nested[1], parents + (name,)))
            else:
                raise ValueError('Unsupported NSIS extension instruction: ' + line)
        return result

    shared = sorted(msi_extensions & collect('MacroAllExtensions'))
    if not shared:
        raise ValueError('No shared MSI/NSIS file handlers')
    # A balanced predicate avoids a duplicated whitelist in registration and
    # cleanup, and has no string-length limit as the inventories grow.
    lines = ['; Generated by msi-associations.py; do not edit.',
             '!macro MsiCompatibilityExtension EXT RESULT',
             '  StrCpy ${RESULT} 0']
    for index, extension in enumerate(shared):
        branch = 'If' if index == 0 else 'OrIf'
        lines.append('  ${%s} ${EXT} == "%s"' % (branch, extension))
    lines += ['    StrCpy ${RESULT} 1', '  ${EndIf}', '!macroend', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--nsis-extensions', type=Path,
                        help='Generate the shared NSIS compatibility predicate')
    args = parser.parse_args()
    if args.nsis_extensions:
        text = generate_nsis(args.source, args.nsis_extensions)
    else:
        text = generate(args.source)
    args.output.write_text(text, encoding='utf-8')
